#!/usr/bin/env bash
# Render drive_automation/config.env for a wall PC from walls/<panel>.env
# Usage: ./scripts/render_config_env.sh walls/my-panel.env > config.env
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WALL_ENV="${1:-}"

if [[ -z "${WALL_ENV}" ]]; then
  echo "Usage: $0 walls/<panel>.env" >&2
  exit 1
fi
if [[ "${WALL_ENV}" != /* ]]; then
  WALL_ENV="${ROOT}/${WALL_ENV}"
fi
if [[ ! -f "${WALL_ENV}" ]]; then
  echo "Wall env not found: ${WALL_ENV}" >&2
  exit 1
fi

# shellcheck disable=SC1090
if [[ -f "${ROOT}/walls/_shared.env" ]]; then
  source "${ROOT}/walls/_shared.env"
fi
# shellcheck disable=SC1090
source "${WALL_ENV}"

: "${WALL_IP:?Set WALL_IP in wall env}"
: "${WALL_SSH_USER:?Set WALL_SSH_USER in wall env}"

REMOTE_HOME="/home/${WALL_SSH_USER}"
PROJECT_DIR="${REMOTE_HOME}/${DRIVE_LAB_DIR:-drive_automation}"
PANEL_CFG="${PROJECT_DIR}/panels_config.yml"

cat <<EOF
# Generated by scripts/render_config_env.sh from $(basename "${WALL_ENV}")
# Wall: ${WALL_NAME:-${WALL_IP}} (${WALL_SSH_USER}@${WALL_IP})
# Re-run: ./setup_wall.sh walls/$(basename "${WALL_ENV}")

DRIVE_EV_URL=${DRIVE_EV_URL:-http://10.91.1.51:8091}
DRIVE_LB2_URL=${DRIVE_LB2_URL:-http://10.91.1.66:8080}
DRIVE_OPERATOR=${DRIVE_OPERATOR:-Automation}
DRIVE_PASSWORD=${DRIVE_PASSWORD:-}
DRIVE_DASHBOARD_PORT=${DRIVE_DASHBOARD_PORT:-8765}
DRIVE_EV_MAX_AMPS=${DRIVE_EV_MAX_AMPS:-30}
DRIVE_LB2_START_DELAY_SEC=${DRIVE_LB2_START_DELAY_SEC:-10}
DRIVE_TELEMETRY_INTERVAL_SEC=${DRIVE_TELEMETRY_INTERVAL_SEC:-0.5}
DRIVE_SLEW_A_PER_S=${DRIVE_SLEW_A_PER_S:-13}

USE_GATEWAY=${USE_GATEWAY:-1}
GATEWAY_SSH_HOST=${GATEWAY_SSH_HOST:-}
GATEWAY_SSH_USER=${GATEWAY_SSH_USER:-root}
# With WALL_GATEWAY_SERIAL set, default to spanssh (not LAN publickey).
GATEWAY_SSH_AUTH=${GATEWAY_SSH_AUTH:-$([ -n "${WALL_GATEWAY_SERIAL:-${GATEWAY_SERIAL:-}}" ] && echo spanssh || echo auto)}
GATEWAY_SSH_IDENTITY=${GATEWAY_SSH_IDENTITY:-'~/.ssh/id_ecdsa'}
GATEWAY_SERIAL=${GATEWAY_SERIAL:-${WALL_GATEWAY_SERIAL:-}}

GATEWAY_SERIALS=${GATEWAY_SERIALS:-${WALL_GATEWAY_SERIAL:-}}
GATEWAY_CAPTURE_CONFIG_PATH=${PANEL_CFG}
PANEL_CONFIG_PATH=${PANEL_CFG}
PANEL_SSH_PASS=${PANEL_SSH_PASS:-}

CAPTURE_SSH_HOST=${WALL_IP}
CAPTURE_SSH_USER=${WALL_SSH_USER}
CAPTURE_SSH_PASS=${CAPTURE_SSH_PASS:-}

DRIVE_SBX_PORT=${DRIVE_SBX_PORT:-/dev/ttyUSB0}
DRIVE_SBX_SERIAL=${DRIVE_SBX_SERIAL:-}
DRIVE_SBX_SERIAL_STRICT=${DRIVE_SBX_SERIAL_STRICT:-1}
EOF
